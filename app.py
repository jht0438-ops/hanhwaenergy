def krw(v):
    if pd.isna(v): return '-'
    if abs(v) >= 10000: return f'{v/10000:,.2f}조'
    return f'{v:,.0f}억'

def kpi(label, value, help_text=None):
    st.metric(label, krw(value), help=help_text)

